def _as_list(value: Any) -> list:
    if value is None:
        return []
    if isinstance(value, str):
        text = value.strip()
        if not text or text.lower() in {"nan", "null"}:
            return []
        for sep in (";", "|"):
            text = text.replace(sep, ",")
        return [part.strip() for part in text.split(",") if part.strip()]
    if isinstance(value, (list, tuple, set)):
        return [str(v).strip() for v in value if str(v).strip()]
    raise TypeError(f"expected a list or delimited string, got {type(value).__name__}")


def as_bool(value: Any, field: str) -> bool:
    """Coerce spreadsheet-style booleans; raise on anything ambiguous."""
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if value in (0, 1):
            return bool(value)
        raise ValueError(f"{field}: expected a boolean, got {value!r}")
    if isinstance(value, str):
        text = value.strip().lower()
        if text in {"true", "yes", "y", "1", "t"}:
            return True
        if text in {"false", "no", "n", "0", "f", ""}:
            return False
    raise ValueError(f"{field}: expected a boolean, got {value!r}")


def normalise_intent(value: Any) -> str | None:
    """Accept a code (``PP``), a full name, or a case variant; return the code."""
    if value is None:
        return None
    text = str(value).strip()
    if not text or text.lower() in {"nan", "none", "null"}:
        return None
    upper = text.upper().replace(" ", "_").replace("-", "_")
    if upper in INTENT_CODES:
        return upper
    lookup = {name.lower(): code for code, name in INTENT_CODES.items()}
    lookup["out_of_scope"] = "OOS"
    lookup["outofscope"] = "OOS"
    return lookup.get(text.lower().replace("-", "_"))


def _normalise_choice(value: Any, choices: Sequence[str], field: str) -> str | None:
    if value is None:
        return None
    text = str(value).strip().lower().replace(" ", "_").replace("-", "_")
    if not text or text in {"nan", "null"}:
        return None
    if text not in choices:
        raise ValueError(f"{field}: {value!r} is not one of {list(choices)}")
    return text


def normalise_record(record: Mapping[str, Any]) -> dict:
    """Return a clean, typed copy of an annotation record.

    Unknown keys are preserved (e.g. timing metadata from the local UI) but
    are not required.  Values that cannot be normalised raise ``ValueError``
    so the caller can quarantine the whole import instead of silently
    dropping rows.
    """
    out: dict[str, Any] = {}
    out["annotator"] = str(record.get("annotator", "")).strip()
    out["item_id"] = str(record.get("item_id", "")).strip()

    intent = normalise_intent(record.get("intent"))
    out["intent"] = intent

    multi = [normalise_intent(v) for v in _as_list(record.get("multi_intent"))]
    if any(v is None for v in multi):
        bad = [v for v in record.get("multi_intent") if normalise_intent(v) is None]
        raise ValueError(f"multi_intent: unknown code(s) {bad}")
    out["multi_intent"] = list(dict.fromkeys(multi))

    if "out_of_scope" in record and record["out_of_scope"] not in (None, ""):
        out["out_of_scope"] = as_bool(record["out_of_scope"], "out_of_scope")
    else:
        out["out_of_scope"] = None

    safety = _normalise_choice(record.get("safety"), SAFETY_LABELS, "safety")
    out["safety"] = safety

    context = [
        _normalise_choice(v, CONTEXT_LABELS, "missing_context")
        for v in _as_list(record.get("missing_context"))
    ]
    if any(v is None for v in context):
        raise ValueError(f"missing_context: unknown value(s) {record.get('missing_context')!r}")
    out["missing_context"] = list(dict.fromkeys(context))

    for field, choices in (
        ("retrieval_relevance", RELEVANCE_LABELS),
        ("answer_quality", QUALITY_LABELS),
        ("answer_safety", SAFETY_LABELS),
    ):
        raw = record.get(field) or {}
        if isinstance(raw, str):
            raise ValueError(f"{field}: expected a mapping of candidate id to label")
        if not isinstance(raw, Mapping):
            raise ValueError(f"{field}: expected a mapping of candidate id to label")
        cleaned: dict[str, str] = {}
        for candidate, label in raw.items():
            key = str(candidate).strip()
            if not key:
                continue
            value = _normalise_choice(label, choices, f"{field}[{key}]")
            if value is not None:
                cleaned[key] = value
        out[field] = cleaned

    out["ambiguous"] = as_bool(record.get("ambiguous", False), "ambiguous")
    out["uncertain"] = as_bool(record.get("uncertain", False), "uncertain")

    certainty = record.get("certainty")
    if certainty in (None, "", "nan"):
        out["certainty"] = None
    else:
        try:
            value = int(certainty)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"certainty: expected 1, 2 or 3, got {certainty!r}") from exc
        if value not in CERTAINTY_LABELS:
            raise ValueError(f"certainty: expected 1, 2 or 3, got {value}")
        out["certainty"] = value

    out["notes"] = str(record.get("notes", "") or "").strip()
    out["created_at"] = str(record.get("created_at", "") or "").strip()

    for key, value in record.items():
        if key not in out:
            out[key] = value
    return out


def validate_record(record: Mapping[str, Any], candidate_ids: Iterable[str] | None = None) -> list[str]:
    """Return a list of human-readable validation errors (empty means valid).

    ``candidate_ids`` is the set of opaque candidate ids shown for this item;
    when given, labels for unknown ids are rejected rather than ignored.
    """
    errors: list[str] = []
    try:
        rec = normalise_record(record)
    except (TypeError, ValueError) as exc:
        return [str(exc)]

    if not rec["annotator"]:
        errors.append("annotator: required")
    if not rec["item_id"]:
        errors.append("item_id: required")

    if rec["intent"] is None:
        errors.append("intent: required (one of " + ", ".join(INTENT_ORDER) + ")")

    if rec["out_of_scope"] is None:
        errors.append("out_of_scope: required")
    else:
        if rec["out_of_scope"] and rec["intent"] != "OOS":
            errors.append("out_of_scope: true requires intent == OOS")
        if rec["intent"] == "OOS" and not rec["out_of_scope"]:
            errors.append("intent: OOS requires out_of_scope == true")

    if rec["multi_intent"]:
        if rec["intent"] in INTENT_ORDER and rec["intent"] not in rec["multi_intent"]:
            errors.append("multi_intent: must contain the primary intent when non-empty")
        if "OOS" in rec["multi_intent"] and rec["intent"] != "OOS":
            errors.append("multi_intent: OOS cannot be combined with an agriculture intent")
        if len(rec["multi_intent"]) < 2:
            errors.append("multi_intent: use an empty list for single-intent queries")

    if rec["safety"] is None:
        errors.append("safety: required")

    if "none" in rec["missing_context"] and len(rec["missing_context"]) > 1:
        errors.append("missing_context: 'none' cannot be combined with other values")

    if candidate_ids is not None:
        allowed = {str(c) for c in candidate_ids}
        for field in CANDIDATE_TASKS:
            unknown = sorted(set(rec[field]) - allowed)
            if unknown:
                errors.append(f"{field}: unknown candidate id(s) {unknown}; expected a subset of {sorted(allowed)}")

    return errors


def is_complete(record: Mapping[str, Any], candidate_ids: Iterable[str]) -> list[str]:
    """Return the names of tasks that are still unanswered for this record."""
    missing: list[str] = []
    try:
        rec = normalise_record(record)
    except (TypeError, ValueError):
        return list(QUERY_TASKS) + list(CANDIDATE_TASKS)
    if rec["intent"] is None:
        missing.append("intent")
    if rec["out_of_scope"] is None:
        missing.append("out_of_scope")
    if rec["safety"] is None:
        missing.append("safety")
    if not rec["missing_context"]:
        missing.append("missing_context")
    for field in CANDIDATE_TASKS:
        for candidate in candidate_ids:
            if str(candidate) not in rec[field]:
                missing.append(f"{field}:{candidate}")
    return missing
