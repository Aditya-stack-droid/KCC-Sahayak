"""Label schema and validation for the Batch B human annotation pilot.

The schema is deliberately explicit: every field an annotator can set is
validated here, so an imported sheet either conforms exactly or is rejected
with a message.  No label is ever generated by this module — it only checks
and normalises labels that people typed.

The intent label set is the existing ten QueryType categories plus ``OOS``
(out of scope).  ``OOS`` is *not* the same as ``OT``: ``OT`` means "an
agriculture question that does not fit the other nine topics" while ``OOS``
means "not an agriculture question at all".
"""

